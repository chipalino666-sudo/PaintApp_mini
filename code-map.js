/** Код цвета из названия: «563 Schwarz B 3.5 ltr», «Краска Brulex MIX 110B» → 563 / 110. */
function paintCodeOf(name) {
  const match = /(?:^|\s)(\d{3})(?=[A-Za-zА-Яа-я]|\s|$)/.exec(String(name || ''));
  return match ? match[1] : '';
}

/** Если в поиске введён код — возвращаем все его эквиваленты, иначе null. */
function codeAlternatives(query) {
  const text = String(query || '').trim();

  if (!/^\d{2,4}$/.test(text)) return null;

  const codes = new Set([text]);

  for (const [brutex, standox] of codePairs) {
    if (brutex === text) codes.add(standox);
    if (standox === text) codes.add(brutex);
  }

  return codes;
}

/** Второе имя для материала: «Standox 570» — или пустая строка. */
function paintAliasOf(name) {
  const code = paintCodeOf(name);
  if (!code) return '';

  const aliases = [];

  for (const [brutex, standox] of codePairs) {
    if (brutex === code) aliases.push('Standox ' + standox);
    if (standox === code) aliases.push('Brulex ' + brutex);
  }

  return aliases.join(', ');
}